import Foundation

/// Turns saved benchmark JSON into docs/BENCHMARKS.md and the README numbers block, so no number in
/// the docs is ever typed by hand.
public enum BenchReport {
    public static func markdown(_ results: [BenchResult]) -> String {
        var out = "# Benchmarks\n\n"
        out += "Generated by `ram bench report` from the JSON files in `bench/results/`. Do not edit by hand.\n\n"
        out += "Method: every trial runs a **relief** arm (macOS's memory-pressure signal at critical) and a "
        out += "**control** arm (identical timing, no signal) in a seeded random order with a cooldown between arms. "
        out += "Numbers are phys_footprint (Activity Monitor's Memory column) summed per app; apps busy during the 2 s "
        out += "baseline and apps that started or quit mid-window are not counted. Welch's t-test compares the arms.\n\n"
        for r in results.sorted(by: { $0.startedAt < $1.startedAt }) {
            out += "## \(r.scenario) · \(date(r.startedAt)) · \(r.machine.summary) · \(r.machine.osVersion)\n\n"
            out += "- signal held \(Format.duration(Double(r.holdMs) / 1000)), settle \(Format.duration(Double(r.settleMs) / 1000)), "
            out += "cooldown \(Format.duration(r.cooldownS)), seed \(r.seed)\n"
            for n in r.notes { out += "- \(n)\n" }
            if let redone = r.redone, !redone.isEmpty {
                out += "- arms thrown away and run again (\(redone.count)): " + redone.joined(separator: "; ") + "\n"
            }
            out += "\n| Metric | Relief (mean ± sd) | Control (mean ± sd) | n | Welch t | p | Cohen's d |\n"
            out += "|---|---:|---:|---:|---:|---:|---:|\n"
            for s in r.summaries {
                let (fmt, sdFmt) = formatters(s.metric)
                let w = s.welch
                out += "| \(s.metric) | \(fmt(s.relief.mean)) ± \(sdFmt(s.relief.sd)) | \(fmt(s.control.mean)) ± \(sdFmt(s.control.sd)) "
                out += "| \(s.relief.n)/\(s.control.n) | \(w.map { String(format: "%.2f", $0.t) } ?? "—") "
                out += "| \(w.map { pValue($0.p) } ?? "—") | \(w.map { String(format: "%.2f", $0.cohenD) } ?? "—") |\n"
            }
            out += "\n"
            if let best = r.arms.filter({ $0.arm == "relief" }).max(by: { $0.headlineBytes < $1.headlineBytes }) {
                let gains = best.topApps.filter { $0.delta > 0 }.prefix(5)
                    .map { "\($0.name) \(Format.bytes($0.delta, signed: true))" }.joined(separator: ", ")
                out += "Best relief arm (trial \(best.trial)): \(Format.bytes(best.headlineBytes, signed: true)) net"
                out += gains.isEmpty ? ".\n\n" : "; \(gains).\n\n"
            }
        }
        return out
    }

    /// Bullet summary for the README, from the most recent result of each scenario.
    public static func readmeBlock(_ results: [BenchResult]) -> String {
        var latest: [String: BenchResult] = [:]
        for r in results where (latest[r.scenario]?.startedAt ?? .distantPast) < r.startedAt { latest[r.scenario] = r }
        var lines: [String] = []
        for scenario in ["real", "synthetic", "perf"] {
            guard let r = latest[scenario] else { continue }
            for s in r.summaries {
                let (fmt, _) = formatters(s.metric)
                let w = s.welch.map { $0.p < 0.001 ? ", p < 0.001" : ", p = \(pValue($0.p))" } ?? ""
                lines.append("- **\(scenario)** · \(s.metric): relief \(fmt(s.relief.mean)) vs control \(fmt(s.control.mean)) (n = \(s.relief.n)\(w)) on \(r.machine.summary)")
            }
        }
        return lines.joined(separator: "\n")
    }

    static func formatters(_ metric: String) -> ((Double) -> String, (Double) -> String) {
        if metric.contains("bytes") { return ({ Format.bytes(Int64($0), signed: true) }, { Format.bytes(Int64($0)) }) }
        if metric.contains("seconds") { return ({ String(format: "%.2f s", $0) }, { String(format: "%.2f", $0) }) }
        return ({ String(format: "%.0f", $0) }, { String(format: "%.0f", $0) })
    }

    static func pValue(_ p: Double) -> String { p < 0.001 ? "< 0.001" : String(format: "%.3f", p) }

    static func date(_ d: Date) -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd HH:mm"
        return f.string(from: d)
    }
}
