#!/bin/zsh
# Runs every automatable acceptance criterion (spec section 11) and writes TEST_RESULTS.md.
# Ends with exactly one line: ACCEPTANCE: <passed>/9 PASS
set -u
cd "$(dirname "$0")/.."
OUT=TEST_RESULTS.md
pass=0
results=()
record() { # name status detail
  results+=("| $1 | $2 | $3 |")
  [[ $2 == PASS ]] && (( pass += 1 ))
  print -r -- "$2  $1 — $3"
}
latest() { ls -t bench/results/*-$1.json 2>/dev/null | head -1 }

# 1. Build + unit + no-root integration tests
if scripts/with-build-lock.sh swift build -j 2 >/tmp/ram-accept-build.log 2>&1 && \
   RAM_LIVE_TESTS=1 scripts/with-build-lock.sh swift test -j 2 >/tmp/ram-accept-test.log 2>&1; then
  n=$(grep -Eo "Test run with [0-9]+ tests" /tmp/ram-accept-test.log | tail -1 | grep -Eo "[0-9]+")
  record "1 build + tests" PASS "$n tests passed"
else
  record "1 build + tests" FAIL "see /tmp/ram-accept-test.log"
fi

# 2. Root end-to-end with the helper
if [[ -f /Library/LaunchDaemons/ca.bryanyao.DownloadMoreRAM.helper.plist ]]; then
  if grep -q "Relief end to end (helper)\" passed" /tmp/ram-accept-test.log; then
    record "2 helper end-to-end" PASS "cachehog freed >= 90%, dumbhog flat, pressure restored"
  else
    record "2 helper end-to-end" FAIL "suite did not pass (see /tmp/ram-accept-test.log)"
  fi
else
  record "2 helper end-to-end" PENDING "helper not installed (NEEDS_HUMAN H1)"
fi

# 3. Real download beats control drift by >= 3x
f=$(latest real)
if [[ -n $f ]]; then
  verdict=$(python3 - "$f" <<'PY'
import json,sys
d=json.load(open(sys.argv[1]))
s=[x for x in d["summaries"] if x["metric"]=="net bytes returned"][0]
r,c=s["relief"]["mean"],s["control"]["mean"]
ok = r>0 and r>=3*max(abs(c),1)
print(("PASS" if ok else "FAIL")+f" relief {r/2**20:.0f} MiB vs control {c/2**20:.0f} MiB (n={s['relief']['n']})")
PY
)
  record "3 real download vs control" ${verdict%% *} "${verdict#* } · $f"
else
  record "3 real download vs control" PENDING "no bench/results/*-real.json yet"
fi

# 4. Wall model reproduces the kernel's conditions (unit tests) and reads low under normal load
if grep -q "Suite \"Wall model\" passed" /tmp/ram-accept-test.log; then
  pct=$(.build/arm64-apple-macosx/debug/ram status --json 2>/dev/null | python3 -c "import json,sys; print(round(json.load(sys.stdin)['wall']['percent']))" 2>/dev/null)
  record "4 wall model" PASS "unit suite passed (stuck-swap = imminent, segment/page/disk limits); live reading ${pct:-?}%"
else
  record "4 wall model" FAIL "wall model suite failed"
fi

# 5. Performance benchmark exists with n >= 5 per arm (reported honestly whatever the direction)
f=$(latest perf)
if [[ -n $f ]]; then
  verdict=$(python3 - "$f" <<'PY'
import json,sys
d=json.load(open(sys.argv[1]))
s=[x for x in d["summaries"] if x["metric"]=="workload seconds"]
if not s: print("FAIL no workload metric"); sys.exit()
s=s[0]; w=s.get("welch") or {}
ok = s["relief"]["n"]>=5 and s["control"]["n"]>=5
print(("PASS" if ok else "FAIL")+f" relief {s['relief']['mean']:.2f}s vs control {s['control']['mean']:.2f}s, p={w.get('p',float('nan')):.3f}")
PY
)
  record "5 performance bench" ${verdict%% *} "${verdict#* }"
else
  record "5 performance bench" PENDING "no bench/results/*-perf.json yet"
fi

# 6. App resource budgets
if [[ -f bench/app-budget.json ]]; then
  verdict=$(python3 - <<'PY'
import json
d=json.load(open("bench/app-budget.json"))
ok = d["idle_cpu_pct"]<0.2 and d["footprint_mb"]<30 and d["wakeups_per_s"]<0.5
print(("PASS" if ok else "FAIL")+f" idle {d['idle_cpu_pct']:.3f}% CPU, {d['footprint_mb']:.1f} MB, {d['wakeups_per_s']:.2f} wakeups/s")
PY
)
  record "6 app budgets" ${verdict%% *} "${verdict#* }"
else
  record "6 app budgets" PENDING "run scripts/measure-app.sh"
fi

# 7. Restore paths: code review sign-off + tests
if grep -qi "restore paths: verified" docs/reviews/code-safety.md 2>/dev/null; then
  record "7 never stuck in simulated pressure" PASS "review sign-off in docs/reviews/code-safety.md"
else
  record "7 never stuck in simulated pressure" PENDING "awaiting docs/reviews/code-safety.md"
fi

# 8. README numbers are generated
if grep -q "Generated by \`ram bench report\`" README.md && ! grep -q "Filled with the output of a real" README.md; then
  record "8 generated README numbers" PASS "bench block + real demo output present"
else
  record "8 generated README numbers" PENDING "README bench/demo blocks not filled from real runs yet"
fi

# 9. Two independent reviews, all findings addressed
if grep -qi "status: all findings addressed" docs/reviews/code-safety.md 2>/dev/null && \
   grep -qi "status: all findings addressed" docs/reviews/claims-evidence.md 2>/dev/null; then
  record "9 independent reviews" PASS "code/safety + claims/evidence"
else
  record "9 independent reviews" PENDING "docs/reviews/*.md not complete"
fi

{
  print "# Test results"
  print
  print "Generated by scripts/acceptance.sh on $(date '+%Y-%m-%d %H:%M %Z') ($(git rev-parse --short HEAD))."
  print
  print "| Criterion | Status | Evidence |"
  print "|---|---|---|"
  for r in $results; do print -r -- $r; done
  print
  print "ACCEPTANCE: $pass/9 PASS"
} > $OUT
print "ACCEPTANCE: $pass/9 PASS"
