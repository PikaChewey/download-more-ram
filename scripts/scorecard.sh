#!/bin/zsh
# The v2 scorecard (spec: ~/Documents/Goals/download-more-ram-v2.md). Every check reads a file a tool
# produced; review verdict lines are written only by the independent reviewer.
# Ends with exactly one line: SCORECARD: <passed>/10 PASS
set -u
cd "$(dirname "$0")/.."
RECEIPTS="$HOME/Library/Application Support/DownloadMoreRAM/receipts"
pass=0
row() { print -r -- "$2  $1 — $3"; [[ $2 == PASS ]] && (( pass += 1 )) }
newest() { ls -t $~1 2>/dev/null | head -1 }

# S1: one pre-registered relief-vs-control run, n >= 5 per arm, reported in README whatever the p
f=$(newest "bench/results/*-real.json")
if [[ -n $f ]]; then
  out=$(python3 - "$f" <<'PY'
import json,sys
d=json.load(open(sys.argv[1])); s=[x for x in d["summaries"] if x["metric"]=="net bytes returned"][0]
w=s.get("welch") or {}
ok=s["relief"]["n"]>=5 and s["control"]["n"]>=5
print(("OK" if ok else "N"), f"relief {s['relief']['mean']/2**20:+.0f} MiB vs control {s['control']['mean']/2**20:+.0f} MiB, n={s['relief']['n']}/{s['control']['n']}, p={w.get('p',float('nan')):.3f}")
PY
)
  if [[ ${out%% *} == OK ]] && grep -q "Generated by \`ram bench report\`" README.md; then row S1 PASS "${out#* }"; else row S1 FAIL "${out#* } (README block missing or n < 5)"; fi
else row S1 FAIL "no bench/results/*-real.json"; fi

# S2: a real receipt whose headline is the sum of >= 2 independently measured levers
f=$(newest "$RECEIPTS/*.json")
if [[ -n $f ]]; then
  out=$(python3 - "$f" <<'PY'
import json,sys
d=json.load(open(sys.argv[1])); L=d.get("levers") or []
measured=[l for l in L if l.get("bytes") is not None]
s=sum(l["bytes"] for l in measured)
ok=len(measured)>=2 and s==d["headlineBytes"] and any(l["kind"]!="signal" for l in measured)
print(("OK" if ok else "N"), " + ".join(f"{l['kind']} {l['bytes']/2**20:+.0f} MiB" for l in measured) or "no levers", f"= {d['headlineBytes']/2**20:+.0f} MiB")
PY
)
  [[ ${out%% *} == OK ]] && row S2 PASS "${out#* }" || row S2 FAIL "${out#* } ($f)"
else row S2 FAIL "no receipts"; fi

# S3: performance reported honestly (n >= 5), or a documented honest null
f=$(newest "bench/results/*-perf.json")
if [[ -n $f ]]; then
  out=$(python3 - "$f" <<'PY'
import json,sys
d=json.load(open(sys.argv[1])); s=[x for x in d["summaries"] if x["metric"]=="workload seconds"][0]; w=s.get("welch") or {}
ok=s["relief"]["n"]>=5 and s["control"]["n"]>=5
print(("OK" if ok else "N"), f"workload {s['relief']['mean']:.2f}s after relief vs {s['control']['mean']:.2f}s after control, p={w.get('p',float('nan')):.3f}")
PY
)
  [[ ${out%% *} == OK ]] && row S3 PASS "${out#* }" || row S3 FAIL "${out#* }"
elif grep -q "honest null" bench/logs/perf-gate.log 2>/dev/null; then row S3 PASS "not run: $(tail -1 bench/logs/perf-gate.log)"
else row S3 FAIL "no perf result"; fi

# S4: idle cost of the menu bar app
if [[ -f bench/app-budget.json ]]; then
  out=$(python3 -c "
import json; d=json.load(open('bench/app-budget.json'))
ok=d['idle_cpu_pct']<0.2 and d['footprint_mb']<30 and d['wakeups_per_s']<0.5
print(('OK' if ok else 'N'), f\"{d['idle_cpu_pct']:.3f}% CPU, {d['footprint_mb']:.1f} MB, {d['wakeups_per_s']:.2f} wakeups/s over {d['seconds']:.0f}s\")")
  [[ ${out%% *} == OK ]] && row S4 PASS "${out#* }" || row S4 FAIL "${out#* }"
else row S4 FAIL "run scripts/measure-app.sh 180"; fi

# S5: safety review closed by the independent reviewer
if grep -qi "status: all findings addressed" docs/reviews/code-safety.md 2>/dev/null && grep -qi "restore paths: verified" docs/reviews/code-safety.md; then
  row S5 PASS "reviewer verdict in docs/reviews/code-safety.md"
else row S5 FAIL "open findings in docs/reviews/code-safety.md"; fi

# S6: tests (uses the newest acceptance/test log, or runs the suite)
log=/tmp/ram-scorecard-test.log
scripts/with-build-lock.sh swift test -j 2 > $log 2>&1
n=$(grep -Eo "Test run with [0-9]+ tests" $log | tail -1 | grep -Eo "[0-9]+")
if grep -q "Test run with .* passed" $log && (( ${n:-0} >= 120 )); then row S6 PASS "$n tests, 0 failures"
else row S6 FAIL "${n:-?} tests; $(grep -c '✘' $log) failure lines (see $log)"; fi

# S7: time to value
if [[ -f bench/first-run.json ]]; then
  out=$(python3 -c "
import json; d=json.load(open('bench/first-run.json'))
ok=d['commands']<=3 and d['doctor_fast_s']<1 and d['receipt_created']
print(('OK' if ok else 'N'), f\"{d['commands']} commands to a receipt, doctor --fast {d['doctor_fast_s']:.2f}s\")")
  [[ ${out%% *} == OK ]] && row S7 PASS "${out#* }" || row S7 FAIL "${out#* }"
else row S7 FAIL "run scripts/first-run-check.sh"; fi

# S8: demo assets rendered from one real recording
if [[ -f docs/demo.svg && -f docs/share-card.png && -f docs/clip/download.mp4 && -f docs/demo-source.json ]] && \
   python3 -c "import json,hashlib,sys; d=json.load(open('docs/demo-source.json')); sys.exit(0 if hashlib.sha256(open(d['recording'],'rb').read()).hexdigest()==d['sha256'] else 1)" 2>/dev/null; then
  row S8 PASS "demo.svg, share-card.png, clip/download.mp4 from $(python3 -c "import json; print(json.load(open('docs/demo-source.json'))['recording'])")"
else row S8 FAIL "demo assets missing or not traceable to a recording"; fi

# S9: UI matches DESIGN.md
blur=$(grep -l "NSVisualEffectView" Sources/RAMApp/*.swift 2>/dev/null | wc -l | tr -d ' ')
tint=$(grep -l "contentTintColor" Sources/RAMApp/*.swift 2>/dev/null | wc -l | tr -d ' ')
if [[ -f DESIGN.md ]] && python3 scripts/contrast.py >/tmp/ram-contrast.txt 2>&1 && (( blur == 0 && tint == 0 )) && [[ -f bench/app-panel.json ]] && \
   python3 -c "import json,sys; sys.exit(0 if json.load(open('bench/app-panel.json'))['idle_cpu_pct']<3 else 1)"; then
  row S9 PASS "$(tail -1 /tmp/ram-contrast.txt); no blur, template glyph, panel-open CPU ok"
else row S9 FAIL "DESIGN.md/contrast/blur($blur)/tint($tint)/panel CPU: see /tmp/ram-contrast.txt"; fi

# S10: claims review closed by the independent reviewer
if grep -qi "status: all findings addressed" docs/reviews/claims-evidence.md 2>/dev/null; then row S10 PASS "reviewer verdict in docs/reviews/claims-evidence.md"
else row S10 FAIL "docs/reviews/claims-evidence.md not closed"; fi

print "SCORECARD: $pass/10 PASS"
